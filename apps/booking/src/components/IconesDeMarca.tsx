/** Escolhe a marca pela chave do link (`linksDaBarbearia`). */
export function IconeDeMarca({ chave, tamanho }: { chave: 'instagram' | 'whatsapp' | 'google'; tamanho?: number }) {
  if (chave === 'instagram') return <IconeInstagram tamanho={tamanho} />;
  if (chave === 'whatsapp') return <IconeWhatsapp tamanho={tamanho} />;
  return <IconeGoogle tamanho={tamanho} />;
}
